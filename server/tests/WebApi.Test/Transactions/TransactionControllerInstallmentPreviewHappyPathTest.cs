        payload.TotalValue.ShouldBe(400.00m);
        payload.InstallmentCount.ShouldBe(4);
        payload.Rows.Count.ShouldBe(4);
        payload.Rows.Sum(r => r.Value).ShouldBe(400.00m);

        for (var i = 0; i < 4; i++)
        {
            payload.Rows[i].Index.ShouldBe(i + 1);
        }

        var countAfter = await CountTransactionsAsync(branch.Id);
        countAfter.ShouldBe(countBefore);
    }

    [Fact]
    public async Task PreviewInstallment_ShouldReturn200AndMatchWrite_WhenSamePayloadIsUsedForBoth()
    {
        // End-to-end determinism test: preview rows must match persisted rows position-for-position.
        var (user, branch, _, token) = await factory.SeedFullBranchContextAsync("TxnPreviewParity", Role.Manager);
        await factory.SeedOperatorAsync(branch.Id, userId: user.Id);
        var account = await factory.SeedAccountAsync(branch.Id, AccountType.Terminal);
        var category = await factory.SeedCategoryAsync(branch.Id, "Saídas", Direction.Out);
        var transactionType = await factory.SeedTransactionTypeAsync(
            category.Id,
            settlementRule: SettlementRule.OperatorEnteredCheque);

        var firstDueDate = DateTime.Today.AddDays(31);
        var request = new RequestCreateTransactionInstallmentJsonBuilder()
            .WithDate(DateTime.Today)
            .WithDescription("Parity test")
            .WithValue(100.01m)
            .WithTransactionTypeId(transactionType.Id)
            .WithAccountId(account.Id)
            .WithInstallments(
            [
                new RequestCreateTransactionInstallmentItemJson { DueDate = firstDueDate, Value = 33.33m },
                new RequestCreateTransactionInstallmentItemJson { DueDate = firstDueDate.AddDays(15), Value = 33.33m },
                new RequestCreateTransactionInstallmentItemJson { DueDate = firstDueDate.AddDays(45), Value = 33.35m }
            ])
            .Build();

        // 1. Call preview
        var previewResponse = await _client.PostAuthAsync("/transaction/installment/preview", request, token);
        previewResponse.StatusCode.ShouldBe(HttpStatusCode.OK);
        var preview = await previewResponse.ReadContentAsync<ResponseInstallmentPreviewJson>();

        // 2. Call installment create with the same payload
        var createResponse = await _client.PostAuthAsync("/transaction/installment", request, token);
        createResponse.StatusCode.ShouldBe(HttpStatusCode.Created);
        var created = await createResponse.ReadContentAsync<ResponseCreateTransactionInstallmentJson>();

        // 3. Load persisted rows by OriginTransactionId
        var originId = created.Installments[0].Id;
        var persistedRows = await ListInstallmentsAsync(originId, branch.Id);

        persistedRows.Count.ShouldBe(preview.Rows.Count);

        for (var i = 0; i < persistedRows.Count; i++)
        {
            persistedRows[i].DueDate.ShouldBe(preview.Rows[i].DueDate);
            persistedRows[i].Value.ShouldBe(preview.Rows[i].Value);
            persistedRows[i].Description.ShouldBe(preview.Rows[i].Description);
        }
    }

    private async Task<int> CountTransactionsAsync(Guid branchId)
    {
        using var scope = factory.Services.CreateScope();
        var transactionsRepository = scope.ServiceProvider.GetRequiredService<ITransactionsRepository>();
        return await transactionsRepository.CountByBranchIdAsNoTracking(branchId, new TransactionListFilter());
    }

    private async Task<IReadOnlyList<Transaction>> ListInstallmentsAsync(Guid originId, Guid branchId)
    {
        using var scope = factory.Services.CreateScope();
        var transactionsRepository = scope.ServiceProvider.GetRequiredService<ITransactionsRepository>();
        var rows = await transactionsRepository.ListByOriginTransactionIdAndBranchIdAsNoTracking(originId, branchId);
        return rows.OrderBy(t => t.DueDate).ToList();
    }
}
