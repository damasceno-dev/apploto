using System.Net;
using CommonTestUtilities.Requests;
using Microsoft.Extensions.DependencyInjection;
using server.Communication.Requests;
using server.Communication.Responses;
using server.Domain.Entities;
using server.Domain.Entities.Enums;
using server.Domain.Interfaces;
using server.Domain.Models;
using Shouldly;
using WebApi.Test.Infrastructure;
using Xunit;

namespace WebApi.Test.Transactions;

[Collection(ServerApiCollection.Name)]
public class TransactionControllerInstallmentPreviewHappyPathTest(ServerWebApplicationFactory factory)
{
    private readonly HttpClient _client = factory.CreateClient();

    [Fact]
    public async Task PreviewInstallment_ShouldReturn200AndNotPersistRows_WhenManagerSendsManualInstallments()
    {
        var (user, branch, _, token) = await factory.SeedFullBranchContextAsync("TxnPreviewManualMgr", Role.Manager);
        await factory.SeedOperatorAsync(branch.Id, userId: user.Id);
        var account = await factory.SeedAccountAsync(branch.Id, AccountType.Terminal);
        var category = await factory.SeedCategoryAsync(branch.Id, "Saídas", Direction.Out);
        var transactionType = await factory.SeedTransactionTypeAsync(
            category.Id,
            settlementRule: SettlementRule.OperatorEnteredCheque);

        var countBefore = await CountTransactionsAsync(branch.Id);

        var firstDueDate = DateTime.Today.AddDays(30);
        var request = new RequestCreateTransactionInstallmentJsonBuilder()
            .WithDate(DateTime.Today)
            .WithDescription("Cheque preview")
            .WithValue(300.00m)
            .WithTransactionTypeId(transactionType.Id)
            .WithAccountId(account.Id)
            .WithInstallments(
            [
                new RequestCreateTransactionInstallmentItemJson { DueDate = firstDueDate, Value = 100.00m },
                new RequestCreateTransactionInstallmentItemJson { DueDate = firstDueDate.AddDays(30), Value = 100.00m },
                new RequestCreateTransactionInstallmentItemJson { DueDate = firstDueDate.AddDays(60), Value = 100.00m }
            ])
            .Build();

        var httpResponse = await _client.PostAuthAsync("/transaction/installment/preview", request, token);

        httpResponse.StatusCode.ShouldBe(HttpStatusCode.OK);
        var payload = await httpResponse.ReadContentAsync<ResponseInstallmentPreviewJson>();

        payload.TotalValue.ShouldBe(300.00m);
        payload.InstallmentCount.ShouldBe(3);
        payload.Rows.Count.ShouldBe(3);

        for (var i = 0; i < 3; i++)
        {
            payload.Rows[i].Index.ShouldBe(i + 1);
            payload.Rows[i].Value.ShouldBe(100.00m);
            payload.Rows[i].DueDate.ShouldBe(firstDueDate.AddDays(i * 30));
        }

        payload.Rows[0].Description.ShouldBe("CH PRE (1/3) - Cheque preview");
        payload.Rows[1].Description.ShouldBe("CH PRE (2/3) - Cheque preview");
        payload.Rows[2].Description.ShouldBe("CH PRE (3/3) - Cheque preview");

        var countAfter = await CountTransactionsAsync(branch.Id);
        countAfter.ShouldBe(countBefore);
    }

    [Fact]
    public async Task PreviewInstallment_ShouldReturn200AndNotPersistRows_WhenManagerSendsAutoGeneratedInstallments()
    {
        var (user, branch, _, token) = await factory.SeedFullBranchContextAsync("TxnPreviewAutoMgr", Role.Manager);
        await factory.SeedOperatorAsync(branch.Id, userId: user.Id);
        var account = await factory.SeedAccountAsync(branch.Id, AccountType.Terminal);
        var category = await factory.SeedCategoryAsync(branch.Id, "Saídas", Direction.Out);
        var transactionType = await factory.SeedTransactionTypeAsync(
            category.Id,
            settlementRule: SettlementRule.OperatorEnteredCheque);

        var countBefore = await CountTransactionsAsync(branch.Id);

        var baseDueDate = DateTime.Today.AddDays(30);
        var request = new RequestCreateTransactionInstallmentJsonBuilder()
            .WithDate(DateTime.Today)
            .WithValue(400.00m)
            .WithTransactionTypeId(transactionType.Id)
            .WithAccountId(account.Id)
            .WithAutoGeneration(4, baseDueDate)
            .Build();

        var httpResponse = await _client.PostAuthAsync("/transaction/installment/preview", request, token);

        httpResponse.StatusCode.ShouldBe(HttpStatusCode.OK);
