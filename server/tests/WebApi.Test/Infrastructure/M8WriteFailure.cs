using Microsoft.EntityFrameworkCore;

namespace WebApi.Test.Infrastructure;

/// <summary>Task-scoped database trigger for proving whole-transaction rollback, never a production reset route.</summary>
internal sealed class M8WriteFailure(ServerWebApplicationFactory factory, string table, string name) : IAsyncDisposable
{
    public static async Task<M8WriteFailure> Install(ServerWebApplicationFactory factory, string table, string column, Guid value)
    {
        if (!new[] { "Users", "RefreshTokens", "PasswordResetTokens", "Invitations", "BranchUsers", "Operators" }.Contains(table)
            || !new[] { "Id", "UserId", "BranchId" }.Contains(column)) throw new ArgumentException("Unsupported test trigger target.");
        var name = "m8_fail_" + Guid.NewGuid().ToString("N");
        await factory.ReadDb(async db =>
        {
            var sql = $"""
                CREATE FUNCTION {name}() RETURNS trigger LANGUAGE plpgsql AS $$
                BEGIN
                  IF NEW."{column}" = '{value}'::uuid THEN RAISE EXCEPTION 'M8_TEST_COMMIT_FAILURE'; END IF;
                  RETURN NEW;
                END $$;
                CREATE TRIGGER {name} BEFORE INSERT OR UPDATE ON "{table}" FOR EACH ROW EXECUTE FUNCTION {name}();
                """;
            #pragma warning disable EF1002 // Table/column allowlisted; identifier and UUID generated by this test.
            return await db.Database.ExecuteSqlRawAsync(sql);
            #pragma warning restore EF1002
        });
        return new M8WriteFailure(factory, table, name);
    }

    public async ValueTask DisposeAsync()
    {
        await factory.ReadDb(async db =>
        {
            #pragma warning disable EF1002 // Private generated identifier/table from Install.
            return await db.Database.ExecuteSqlRawAsync($"DROP TRIGGER IF EXISTS {name} ON \"{table}\"; DROP FUNCTION IF EXISTS {name}();");
            #pragma warning restore EF1002
        });
    }
}
