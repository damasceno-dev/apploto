// Generates `src/theme/token-adapter.ts` from design/tokens (`pnpm generate:tokens`) and, with
// `--check`, fails on drift or on class names that consume a semantic/domain color that does not
// exist. The generated adapter is the app's single raw-color exemption.
import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import prettier from 'prettier';
import {
  colorVariableNames,
  colorVariables,
  loadTokens,
  nativeTokens,
  readTokenDirectory,
} from './token-resolver.mjs';

const appRoot = fileURLToPath(new URL('..', import.meta.url));
export const tokenDirectory = path.join(appRoot, '..', 'design', 'tokens');
export const adapterPath = path.join(appRoot, 'src', 'theme', 'token-adapter.ts');

export async function renderAdapter(values) {
  const json = (value) => JSON.stringify(value, null, 2);
  const text = `// GENERATED by \`pnpm --filter @loto/mobile generate:tokens\` from design/tokens/*.json — do not edit.
// The single raw-color exemption: semantic and domain colors resolved per theme (no primitive
// names), plus the native typography, spacing, radius, shadow, motion, layer and breakpoint scales.
// \`lint\` fails when this file drifts from the token sources.

export const nativeTokens = ${json(nativeTokens(values))} as const;

/** NativeWind \`vars()\` input per theme: \`--sem-…\` / \`--dom-…\` → resolved color. */
export const colorVariables = ${json({ light: colorVariables(values, 'light'), dark: colorVariables(values, 'dark') })} as const;

/** Every class-consumable color name (\`bg-sem-surface-default\`, \`text-dom-…\`). */
export const colorNames = ${json(colorVariableNames(values))} as const;
`;
  const options = await prettier.resolveConfig(adapterPath);
  return prettier.format(text, { ...options, filepath: adapterPath });
}

const classColor =
  /(?:^|[\s"'`:])(?:bg|text|border(?:-[trblxy])?|outline|ring|shadow|placeholder|decoration|divide|fill|stroke|tint)-((?:sem|dom)-[A-Za-z0-9-]+?)(?:\/\d+)?(?=[\s"'`]|$)/g;

/** Class strings in app source that name a sem/dom color absent from the token set. */
export function unknownColorClasses(source, names) {
  const known = new Set(names);
  const unknown = [];
  for (const match of source.matchAll(classColor)) if (!known.has(match[1])) unknown.push(match[1]);
  return unknown;
}

async function sourceFiles(directory) {
  const files = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const file = path.join(directory, entry.name);
    if (entry.isDirectory()) files.push(...(await sourceFiles(file)));
    else if (/\.tsx?$/.test(entry.name)) files.push(file);
  }
  return files;
}

async function main() {
  const values = loadTokens(readTokenDirectory(tokenDirectory));
  const expected = await renderAdapter(values);
  if (!process.argv.includes('--check')) {
    await writeFile(adapterPath, expected);
    console.log(`Wrote ${path.relative(appRoot, adapterPath)}.`);
    return;
  }
  const errors = [];
  const current = await readFile(adapterPath, 'utf8').catch(() => null);
  if (current !== expected)
    errors.push(
      `${path.relative(appRoot, adapterPath)} is stale: run pnpm --filter @loto/mobile generate:tokens`,
    );
  const names = colorVariableNames(values);
  for (const file of await sourceFiles(path.join(appRoot, 'src'))) {
    if (file === adapterPath) continue;
    for (const name of unknownColorClasses(await readFile(file, 'utf8'), names))
      errors.push(`${path.relative(appRoot, file)}: unknown token color class "${name}"`);
  }
  if (errors.length > 0) {
    console.error(errors.join('\n'));
    process.exitCode = 1;
  } else console.log('Token adapter matches design/tokens; every sem/dom color class exists.');
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href)
  await main();
