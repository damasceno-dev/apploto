import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
const input = await readFile(
  new URL('../../shared/api/openapi/server-api.openapi.json', import.meta.url),
  'utf8',
);
const spec = JSON.parse(input);
const entries = [];
for (const [path, item] of Object.entries(spec.paths))
  for (const [method, operation] of Object.entries(item)) {
    if (!['get', 'post', 'put', 'patch', 'delete'].includes(method)) continue;
    const security = operation.security;
    const tier =
      Array.isArray(security) && security.length === 0
        ? 'anonymous'
        : security?.length === 1 && security[0].IdentityBearer
          ? 'identity'
          : security?.length === 1 && security[0].BranchBearer
            ? 'branch'
            : null;
    if (!tier) throw new Error(`Unsupported security: ${method} ${path}`);
    entries.push([method.toUpperCase(), path, tier]);
  }
entries.sort(
  (a, b) =>
    b[1].split('/').filter((p) => !p.startsWith('{')).length -
    a[1].split('/').filter((p) => !p.startsWith('{')).length,
);
const source = `// Generated by tooling/auth-policy.mjs from the server OpenAPI; do not edit.\n// Input SHA-256: ${createHash('sha256').update(input).digest('hex')}\nimport type { AuthTier } from '@loto/api';\nexport const authPolicy: readonly (readonly [string, string, AuthTier])[] = ${JSON.stringify(entries, null, 2)};\n`;
const target = new URL('../src/data/auth-policy.generated.ts', import.meta.url);
// Prettier is the same workspace formatter used by all generated app metadata.
const { format } = await import('prettier');
const formatted = await format(source, {
  parser: 'typescript',
  singleQuote: true,
  printWidth: 100,
  trailingComma: 'all',
});
if (process.argv.includes('--check')) {
  if ((await readFile(target, 'utf8')) !== formatted)
    throw new Error('Mobile auth policy drift; run generate:auth.');
} else await writeFile(target, formatted);
const names = [
  'RequestCreateTransactionJson',
  'RequestCreateTransactionInstallmentJson',
  'RequestReceiveFiadoPaymentJson',
];
const schemas = {};
function collect(name) {
  if (schemas[name]) return;
  const schema = spec.components.schemas[name];
  if (!schema) throw new Error(`Missing request schema ${name}`);
  schemas[name] = schema;
  for (const ref of JSON.stringify(schema).matchAll(/#\/components\/schemas\/([^"\\]+)/g))
    collect(ref[1]);
}
for (const name of names) collect(name);
const shapes = new URL('../src/data/request-shapes.generated.json', import.meta.url);
const shapeSource = await format(JSON.stringify(schemas), { parser: 'json', printWidth: 100 });
if (process.argv.includes('--check')) {
  if ((await readFile(shapes, 'utf8')) !== shapeSource)
    throw new Error('Mobile request shape drift');
} else await writeFile(shapes, shapeSource);
