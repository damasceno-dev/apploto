// Generates the forwarder allowlist from Shared's committed operation map (Web M2 Phase 4.1).
// Build-time tooling only: it reads the generated contract file; runtime code never deep-imports
// Shared. `--check` fails when the committed table differs (run by `lint`).
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import prettier from 'prettier';

const source = new URL('../../shared/api/src/generated/operations/operations.ts', import.meta.url);
const target = new URL('../src/server/bff/operations.generated.ts', import.meta.url);

/**
 * Operations the browser never reaches through the forwarder: their responses carry credentials,
 * or they start/end a session. Login, renewal, logout and branch session are BFF routes now; Google
 * sign-in, invitation registration and password change get BFF routes with Web M11.
 */
export const bffOwned = [
  'POST /user/login',
  'POST /user/renew-token',
  'POST /user/logout',
  'POST /branch/session',
  'POST /user/google/challenge',
  'POST /user/google/sign-in',
  'POST /invitation/register',
  'POST /user/change-password',
];

export async function render() {
  const { operations } = await import(source.href);
  const keys = new Set(operations.map((operation) => `${operation.method} ${operation.path}`));
  for (const owned of bffOwned) {
    if (!keys.has(owned)) throw new Error(`BFF-owned operation is not in the contract: ${owned}`);
  }
  const forwarded = operations.filter(
    (operation) => !bffOwned.includes(`${operation.method} ${operation.path}`),
  );
  const text = `// Generated by web/tooling/bff-operations.mjs from Shared's committed operation map. Do not edit.
// Operations the forwarder may reach; credential-bearing and session operations are excluded.
export const forwardedOperations = ${JSON.stringify(forwarded)} as const;

export const bffOwnedOperations = ${JSON.stringify(bffOwned)} as const;
`;
  const options = await prettier.resolveConfig(fileURLToPath(target));
  return prettier.format(text, { ...options, filepath: fileURLToPath(target) });
}

if (import.meta.url === new URL(process.argv[1], 'file:').href) {
  const rendered = await render();
  if (process.argv.includes('--check')) {
    const committed = await readFile(target, 'utf8').catch(() => '');
    if (committed !== rendered) {
      console.error('BFF operation table is stale: run `pnpm --filter @loto/web generate:bff`.');
      process.exitCode = 1;
    }
  } else {
    await writeFile(target, rendered);
  }
}
